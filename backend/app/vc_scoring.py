"""
Индекс качества сделок венчурного фонда — простая прозрачная эвристика
(по аналогии с app/scoring.py для стартапов), а не точная финансовая
метрика. "Качество" отдельной сделки непубличного рынка в принципе нельзя
объективно измерить по открытым источникам — вместо этого индекс собирает
три сигнала, которые обычно МОЖНО подтвердить публично и которые косвенно
говорят о том, что рынок/другие инвесторы уже "проверили" сделки фонда:

  + 4 балла, если у фонда есть подтверждённый заметный выход из портфельной
    компании (IPO/M&A) — самый сильный публичный сигнал качества
  + до 3 баллов (по 1 за компанию, максимум 3) — за количество узнаваемых
    портфельных компаний, которые фонд явно называет/подтверждает
  + 3 балла, если фонд специализируется на поздних стадиях/pre-IPO —
    более крупные и более "рыночно проверенные" раунды, обычно с
    co-инвесторами и due diligence, чем на pre-seed

Максимум — 10. Это не заменяет и не оценивает конкретные сделки —
именно поэтому индекс относится к ФОНДУ в целом, а не к отдельной сделке.
"""

LATE_STAGE_KEYWORDS = (
    "поздн", "pre-ipo", "growth", "round b", "round c", "раунд b", "раунд c", "b/c",
)


def compute_quality_index(notable_exit_note, notable_portfolio, stage_focus):
    idx = 0.0
    if notable_exit_note:
        idx += 4
    idx += min(3, len(notable_portfolio or []))
    stage_l = (stage_focus or "").lower()
    if any(k in stage_l for k in LATE_STAGE_KEYWORDS):
        idx += 3
    return round(idx, 1)
