"""
Категоризация компаний на 4 раздела рейтинга по возрасту/стадии.

  young       — моложе 3 лет
  mature      — от 3 до 10 лет
  aged        — старше 10 лет (и всё ещё активно растут — это гарантируется
                отбором записей на этапе исследования/добавления в базу,
                а не проверяется автоматически по формуле)
  early_stage — pre-seed/seed, без выручки или с только начинающейся, но с
                перспективной идеей — ПРИОРИТЕТНАЯ категория: если у записи
                стоит is_early_stage=True, она показывается только в разделе
                "Ранняя стадия", независимо от возраста, и не дублируется в
                возрастных разделах.

Категория вычисляется на лету от текущего года, а не хранится в БД, — так
рейтинг остаётся корректным по мере того, как компании стареют, без
необходимости их периодически "перекатегоризировать" вручную.
"""
import datetime

BUCKETS = ("young", "mature", "aged", "early_stage")

BUCKET_LABELS = {
    "young": "Молодые компании (до 3 лет)",
    "mature": "Зрелые компании (3–10 лет)",
    "aged": "Возрастные компании (>10 лет), но активно растущие",
    "early_stage": "Стартапы ранней стадии (seed / pre-seed)",
}


def current_year() -> int:
    return datetime.datetime.now().year


def compute_bucket(founded, is_early_stage, ref_year=None):
    """Возвращает один из BUCKETS. Если год основания неизвестен и компания
    не помечена как ранняя стадия, по умолчанию относим её к "mature" —
    иначе такие записи вообще не попадали бы ни в один из 4 разделов
    рейтинга. Это временное решение: правильный способ — уточнить точный
    год регистрации через DaData (см. app/enrich.py) и тогда запись
    переместится в свой настоящий раздел автоматически."""
    if is_early_stage:
        return "early_stage"
    if founded is None:
        return "mature"
    ref_year = ref_year or current_year()
    age = ref_year - founded
    if age < 3:
        return "young"
    if age <= 10:
        return "mature"
    return "aged"
